/* Builds the generated parts of the WordPress theme from the static site, so the
   design is never maintained in two places.

   Usage, from the dino-site folder:
     node tools/build-theme.js [preview-dir]

   Generated (do not edit by hand, edit index.html / 404.html / menu.js instead):
     wordpress-theme/dino/index.php
     wordpress-theme/dino/404.php
     wordpress-theme/dino/style.css
     wordpress-theme/dino/js/site.js
     wordpress-theme/dino/js/menu.js
     wordpress-theme/dino/inc/menu-seed.php

   Hand-written (edit directly):
     functions.php, inc/admin-menu.php, js/admin-menu.js, css/admin-menu.css, readme.txt

   If preview-dir is given, a plain HTML preview of the theme output is written there. */
const fs = require('fs'), path = require('path');

const SRC = path.resolve(__dirname, '..');
const OUT = path.join(SRC, 'wordpress-theme', 'dino');
const PREVIEW_DIR = process.argv[2] ? path.resolve(process.argv[2]) : null;

const html = fs.readFileSync(path.join(SRC, 'index.html'), 'utf8');
const html404 = fs.readFileSync(path.join(SRC, '404.html'), 'utf8');
const menuJs = fs.readFileSync(path.join(SRC, 'menu.js'), 'utf8');

fs.mkdirSync(path.join(OUT, 'js'), { recursive: true });
fs.mkdirSync(path.join(OUT, 'inc'), { recursive: true });

// ---- pull the pieces out of index.html
const pick = (re, what) => { const m = html.match(re); if (!m) throw new Error('Could not find ' + what + ' in index.html'); return m[1]; };
const css = pick(/<style>([\s\S]*?)<\/style>/, 'the <style> block').trim();
const loader = pick(/<script src="menu\.js"><\/script>\s*<script>([\s\S]*?)<\/script>/, 'the menu loader script').trim();
const jsonLd = pick(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/, 'the structured data').trim();
const headMeta = pick(/<head>([\s\S]*?)<link rel="preconnect"/, 'the head metadata')
  .replace(/<meta charset[^>]*>\s*/, '').replace(/<meta name="viewport"[^>]*>\s*/, '').trim();
const body = pick(/<body>([\s\S]*?)<!-- Structured data/, 'the page body').trim();

// ---- values a site owner may change become PHP variables (set in the Customizer)
const UBER_RE = /https:\/\/www\.ubereats\.com\/au\/store\/dino-food-&amp;-drink\/[A-Za-z0-9_-]+/g;
const MAPS_RE = /https:\/\/www\.google\.com\/maps\/place\/Dino\+Food[^"]*/g;
function templatize(s) {
  return s
    .replace(UBER_RE, '<?php echo esc_url( $dino_uber ); ?>')
    .replace(MAPS_RE, '<?php echo esc_url( $dino_maps ); ?>')
    .replace(/tel:0468595689/g, 'tel:<?php echo esc_attr( $dino_phone_digits ); ?>')
    .replace(/0468 595 689/g, '<?php echo esc_html( $dino_phone ); ?>');
}
const bodyPhp = templatize(body);

const VARS = `<?php
/**
 * Dino Food & Drink: single page theme. GENERATED by tools/build-theme.js from index.html.
 * Editable values live in Appearance > Customize > Dino Food & Drink.
 * The menu is edited under Menu & Prices in the dashboard.
 */
$dino_phone        = dino_opt( 'dino_phone', '0468 595 689' );
$dino_phone_digits = preg_replace( '/\\s+/', '', $dino_phone );
$dino_uber         = dino_opt( 'dino_uber_url', 'https://www.ubereats.com/au/store/dino-food-&-drink/Jf55f-nFShqsC2IZewn_hA' );
$dino_maps         = dino_opt( 'dino_maps_url', 'https://www.google.com/maps/place/Dino+Food+%26+Drink/@-27.4599475,153.0222981,17z' );
?>
`;

const indexPhp = VARS + `<!DOCTYPE html>
<html <?php language_attributes(); ?>>
<head>
<meta charset="<?php bloginfo( 'charset' ); ?>">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
${headMeta}
<?php wp_head(); ?>
</head>
<body <?php body_class(); ?>>

${bodyPhp}

<script type="application/ld+json">
${jsonLd}
</script>

<?php wp_footer(); ?>
</body>
</html>
`;

// ---- 404.php
const pick404 = (re, what) => { const m = html404.match(re); if (!m) throw new Error('Could not find ' + what + ' in 404.html'); return m[1]; };
const body404 = pick404(/<body>([\s\S]*?)<\/body>/, 'the body').trim();
const head404 = pick404(/<head>([\s\S]*?)<style>/, 'the head')
  .replace(/<meta charset[^>]*>\s*/, '').replace(/<meta name="viewport"[^>]*>\s*/, '')
  .replace(/<link rel="preconnect"[\s\S]*?rel="stylesheet">/, '').trim();
const css404 = pick404(/<style>([\s\S]*?)<\/style>/, 'the styles').trim();
const php404 = `<?php
/* GENERATED by tools/build-theme.js from 404.html. */
$dino_phone        = dino_opt( 'dino_phone', '0468 595 689' );
$dino_phone_digits = preg_replace( '/\\s+/', '', $dino_phone );
?>
<!DOCTYPE html>
<html <?php language_attributes(); ?>>
<head>
<meta charset="<?php bloginfo( 'charset' ); ?>">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
${head404}
<style>
${css404}
</style>
<?php wp_head(); ?>
</head>
<body <?php body_class(); ?>>
${templatize(body404)}
<?php wp_footer(); ?>
</body>
</html>
`;

// ---- style.css
const version = (fs.existsSync(path.join(OUT, 'functions.php'))
  && (fs.readFileSync(path.join(OUT, 'functions.php'), 'utf8').match(/define\(\s*'DINO_VERSION',\s*'([^']+)'/) || [])[1]) || '1.0.0';
const styleCss = `/*
Theme Name: Dino Food & Drink
Theme URI: https://github.com/brobertuy-beep/dino-food-and-drink
Author: Dino Food & Drink
Description: Single page theme for Dino Food & Drink, a family run Vietnamese restaurant in Spring Hill, Brisbane. The menu and prices are edited under Menu & Prices in the dashboard.
Version: ${version}
Requires at least: 5.9
Tested up to: 6.8
Requires PHP: 7.4
License: GNU General Public License v2 or later
License URI: https://www.gnu.org/licenses/gpl-2.0.html
Text Domain: dino
*/

/* GENERATED by tools/build-theme.js from index.html. Edit index.html, then rebuild. */

${css}
`;

// ---- inc/menu-seed.php: the starting menu shown in Menu & Prices before the first save
global.window = {};
new Function('window', menuJs)(global.window);
const M = global.window.DINO_MENU;
if (!M || !M.sections || !M.featured) throw new Error('menu.js did not define window.DINO_MENU');

const feat = {};
M.featured.forEach((f, i) => { feat[f.name.toLowerCase()] = Object.assign({ pos: i + 1 }, f); });
const used = new Set();
const blankItem = () => ({ dish: '', vi: '', desc: '', price: '', price2: '', uber: '', show: true, featured: '', card_label: '', card_desc: '', card_note: '' });

const seed = M.sections.map(s => ({
  title: s.title, note: s.note || '', tag: s.tag || '',
  items: s.items.map(it => {
    const p = [].concat(it.price);
    const f = feat[it.name.toLowerCase()];
    if (f) used.add(it.name.toLowerCase());
    return Object.assign(blankItem(), {
      dish: it.name, vi: it.vi || '', desc: it.desc || '',
      price: p[0] || '', price2: p[1] || '',
      uber: (f && f.uber) || '', featured: f ? String(f.pos) : '',
      card_label: (f && f.badge) || '', card_desc: (f && f.desc) || '', card_note: (f && f.liked) || ''
    });
  })
}));
const extras = M.featured.filter(f => !used.has(f.name.toLowerCase()));
if (extras.length) {
  seed.push({ title: 'Drinks', note: '', tag: '', items: extras.map(f => Object.assign(blankItem(), {
    dish: f.name, price: f.store || '', uber: f.uber || '', featured: String(feat[f.name.toLowerCase()].pos),
    card_label: f.badge || '', card_desc: f.desc || '', card_note: f.liked || ''
  })) });
}

const phpStr = s => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const phpVal = v => typeof v === 'boolean' ? (v ? 'true' : 'false') : phpStr(v);
const phpArr = (obj, ind) => 'array(\n' + Object.keys(obj).map(k => ind + '\t' + phpStr(k) + ' => ' +
  (Array.isArray(obj[k]) ? 'array(\n' + obj[k].map(o => ind + '\t\t' + phpArr(o, ind + '\t\t')).join(',\n') + '\n' + ind + '\t)' : phpVal(obj[k]))
).join(',\n') + '\n' + ind + ')';
const seedPhp = `<?php
/**
 * Starting menu, used until the owners first press Save in Menu & Prices.
 * GENERATED by tools/build-theme.js from menu.js. Do not edit by hand.
 */
if ( ! defined( 'ABSPATH' ) ) { exit; }

return array(
${seed.map(s => '\t' + phpArr(s, '\t')).join(',\n')}
);
`;

fs.writeFileSync(path.join(OUT, 'style.css'), styleCss);
fs.writeFileSync(path.join(OUT, 'index.php'), indexPhp);
fs.writeFileSync(path.join(OUT, '404.php'), php404);
fs.writeFileSync(path.join(OUT, 'js', 'menu.js'), menuJs);
fs.writeFileSync(path.join(OUT, 'js', 'site.js'), '/* GENERATED by tools/build-theme.js from the loader script in index.html. */\n' + loader + '\n');
fs.writeFileSync(path.join(OUT, 'inc', 'menu-seed.php'), seedPhp);

// ---- optional plain HTML preview of the theme output
if (PREVIEW_DIR) {
  fs.mkdirSync(PREVIEW_DIR, { recursive: true });
  const preview = `<!DOCTYPE html>
<html lang="en"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1.0">
${headMeta}
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="https://fonts.googleapis.com/css2?family=Fraunces:opsz,wght@9..144,500;9..144,600;9..144,700;9..144,900&family=Inter:wght@400;500;600;700&display=swap" rel="stylesheet">
<style>${css}</style></head>
<body>
${body}
<script type="application/ld+json">${jsonLd}</script>
<script src="menu.js"></script>
<script>window.DINO_MENU_API = window.DINO_MENU_API_PREVIEW || '';</script>
<script>${loader}</script>
</body></html>`;
  fs.writeFileSync(path.join(PREVIEW_DIR, 'preview.html'), preview);
  fs.writeFileSync(path.join(PREVIEW_DIR, 'menu.js'), menuJs);
  fs.writeFileSync(path.join(PREVIEW_DIR, 'menu-seed.json'), JSON.stringify(seed, null, 1));
}

// ---- report
const leftovers = [];
if (/ubereats\.com/.test(bodyPhp.replace(/<\?php[\s\S]*?\?>/g, ''))) leftovers.push('hard-coded Uber Eats URL remains');
if (/0468 595 689/.test(bodyPhp)) leftovers.push('hard-coded phone remains');
console.log('theme written to', OUT, '(version ' + version + ')');
console.log('seed:', seed.length, 'sections,', seed.reduce((n, s) => n + s.items.length, 0), 'dishes');
console.log('leftovers:', leftovers.length ? leftovers.join('; ') : 'none');
if (PREVIEW_DIR) console.log('preview written to', PREVIEW_DIR);
